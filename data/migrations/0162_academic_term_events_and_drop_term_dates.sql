-- 0162_academic_term_events_and_drop_term_dates.sql
-- Normalizes all academic calendar dates and milestones into a dedicated
-- `academic_term_event` table, and removes `starts_on` and `ends_on` from
-- `academic_term` and associated term query functions.

BEGIN;

-- ============================================================================
-- 1. CREATE academic_term_event TABLE
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.academic_term_event (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_term_id BIGINT NOT NULL REFERENCES public.academic_term(id) ON UPDATE CASCADE ON DELETE CASCADE,
  type             TEXT NOT NULL,
  name             TEXT NOT NULL,
  starts_on        DATE NOT NULL,
  ends_on          DATE NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT chk_academic_term_event_dates CHECK (ends_on >= starts_on)
);

COMMENT ON TABLE public.academic_term_event IS 'Milestones and dates associated with an academic term (enrollment, classes, exams, drop deadlines).';
COMMENT ON COLUMN public.academic_term_event.type IS 'Canonical machine-readable event type (e.g. classes, enrollment_regular, inclusions).';
COMMENT ON COLUMN public.academic_term_event.name IS 'Official human-readable description of the activity published by ITCR.';
COMMENT ON COLUMN public.academic_term_event.starts_on IS 'Start date of the event or window.';
COMMENT ON COLUMN public.academic_term_event.ends_on IS 'End date of the event or window (equals starts_on for single-day events or deadlines).';

-- ============================================================================
-- 2. INDEXES & TRIGGERS
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_academic_term_event_term_type
  ON public.academic_term_event (academic_term_id, type);

CREATE INDEX IF NOT EXISTS idx_academic_term_event_dates
  ON public.academic_term_event (starts_on, ends_on);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'set_timestamp_academic_term_event'
  ) THEN
    CREATE TRIGGER set_timestamp_academic_term_event
      BEFORE UPDATE ON public.academic_term_event
      FOR EACH ROW
      EXECUTE FUNCTION public.trigger_set_timestamp();
  END IF;
END $$;

-- ============================================================================
-- 3. BACKFILL EXISTING DATES FROM academic_term INTO academic_term_event
-- ============================================================================

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'academic_term' 
      AND column_name = 'starts_on'
  ) THEN
    INSERT INTO public.academic_term_event (
      academic_term_id,
      type,
      name,
      starts_on,
      ends_on
    )
    SELECT
      id,
      'classes',
      'Periodo lectivo',
      starts_on,
      COALESCE(ends_on, starts_on)
    FROM public.academic_term
    WHERE starts_on IS NOT NULL;
  END IF;
END $$;

-- ============================================================================
-- 4. RECREATE FUNCTIONS WITHOUT starts_on / ends_on
-- ============================================================================

-- Function: get_active_academic_terms
DROP FUNCTION IF EXISTS public.get_active_academic_terms();
CREATE OR REPLACE FUNCTION public.get_active_academic_terms()
RETURNS TABLE (
  id BIGINT,
  academic_modality_id BIGINT,
  year INTEGER,
  period_number INTEGER,
  external_key TEXT,
  display_name TEXT
)
LANGUAGE plpgsql
SET search_path = public
SECURITY INVOKER
AS $$
BEGIN
  RETURN QUERY
  SELECT DISTINCT
    at.id,
    at.academic_modality_id,
    at.year,
    at.period_number,
    at.external_key,
    at.display_name
  FROM public.academic_term at
  JOIN public.course_offering co ON co.academic_term_id = at.id
  WHERE at.is_active = true
    AND co.is_active = true
  ORDER BY at.year DESC, at.period_number DESC;
END;
$$;

-- Function: get_academic_terms_by_plan
DROP FUNCTION IF EXISTS public.get_academic_terms_by_plan(BIGINT, BIGINT);
CREATE OR REPLACE FUNCTION public.get_academic_terms_by_plan(
  p_study_plan_id BIGINT,
  p_campus_id BIGINT DEFAULT NULL
)
RETURNS TABLE (
  id BIGINT,
  academic_modality_id BIGINT,
  year INTEGER,
  period_number INTEGER,
  external_key TEXT,
  display_name TEXT
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
WITH plan_courses AS (
  SELECT DISTINCT splc.course_id
  FROM public.study_plan_level spl
  JOIN public.study_plan_level_course splc ON splc.study_plan_level_id = spl.id
  WHERE spl.study_plan_id = p_study_plan_id
),
plan_related_courses AS (
  SELECT course_id FROM plan_courses
  UNION
  SELECT cr.to_course_id
  FROM public.course_relation cr
  JOIN public.course c ON c.id = cr.to_course_id
  WHERE cr.study_plan_id = p_study_plan_id
    AND cr.relation_type = 'EQUIVALENT'
    AND cr.from_course_id IN (SELECT course_id FROM plan_courses)
    AND c.name <> c.code
  UNION
  SELECT cr.from_course_id
  FROM public.course_relation cr
  JOIN public.course c ON c.id = cr.from_course_id
  WHERE cr.study_plan_id = p_study_plan_id
    AND cr.relation_type = 'EQUIVALENT'
    AND cr.to_course_id IN (SELECT course_id FROM plan_courses)
    AND c.name <> c.code
),
plan_modalities AS (
  SELECT DISTINCT at.academic_modality_id
  FROM public.course_offering co
  JOIN public.academic_term at ON at.id = co.academic_term_id
  WHERE co.course_id IN (SELECT course_id FROM plan_related_courses)
    AND co.is_active = TRUE
    AND (p_campus_id IS NULL OR co.campus_id = p_campus_id)
)
SELECT DISTINCT
  at.id,
  at.academic_modality_id,
  at.year,
  at.period_number,
  at.external_key,
  at.display_name
FROM public.academic_term at
WHERE EXISTS (
    SELECT 1 FROM plan_modalities pm
    WHERE pm.academic_modality_id = at.academic_modality_id
  )
  AND EXISTS (
    SELECT 1 FROM public.course_offering co
    WHERE co.academic_term_id = at.id
      AND co.is_active = TRUE
      AND (p_campus_id IS NULL OR co.campus_id = p_campus_id)
      AND co.course_id IN (SELECT course_id FROM plan_related_courses)
  )
ORDER BY at.year DESC, at.period_number DESC;
$$;

-- Function: get_course_offering_terms
DROP FUNCTION IF EXISTS public.get_course_offering_terms(BIGINT, BIGINT, BIGINT, BIGINT);
CREATE OR REPLACE FUNCTION public.get_course_offering_terms(
  p_course_id BIGINT,
  p_campus_id BIGINT DEFAULT NULL,
  p_academic_unit_id BIGINT DEFAULT NULL,
  p_study_plan_id BIGINT DEFAULT NULL
)
RETURNS TABLE (
  id BIGINT,
  academic_modality_id BIGINT,
  year INTEGER,
  period_number INTEGER,
  external_key TEXT,
  display_name TEXT
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
WITH placeholder_course AS (
  SELECT c.id AS course_id
  FROM public.course c
  JOIN public.schedule_equivalence_placeholder_course sep
    ON sep.is_active = TRUE
   AND (sep.study_plan_id IS NULL OR sep.study_plan_id = p_study_plan_id)
   AND (
     (sep.course_code IS NOT NULL AND sep.course_code = c.code)
     OR (
       sep.course_name_ilike_pattern IS NOT NULL
       AND c.name ILIKE sep.course_name_ilike_pattern
     )
   )
  WHERE c.id = p_course_id
  LIMIT 1
),
related_courses AS (
  SELECT p_course_id AS course_id
  UNION
  SELECT cr.to_course_id
  FROM public.course_relation cr
  WHERE p_study_plan_id IS NOT NULL
    AND EXISTS (SELECT 1 FROM placeholder_course)
    AND cr.study_plan_id = p_study_plan_id
    AND cr.relation_type = 'EQUIVALENT'
    AND cr.from_course_id = p_course_id
)
SELECT DISTINCT
  at.id,
  at.academic_modality_id,
  at.year,
  at.period_number,
  at.external_key,
  at.display_name
FROM public.course_offering co
JOIN public.academic_term at ON at.id = co.academic_term_id
WHERE co.course_id IN (SELECT course_id FROM related_courses)
  AND co.is_active = TRUE
  AND (p_campus_id IS NULL OR co.campus_id = p_campus_id)
  AND (p_academic_unit_id IS NULL OR co.academic_unit_id = p_academic_unit_id)
  AND EXISTS (
    SELECT 1
    FROM public.course_offering_group cog
    WHERE cog.course_offering_id = co.id
  )
ORDER BY at.year DESC, at.period_number DESC, at.id DESC;
$$;

-- Function: get_professor_offering_terms
DROP FUNCTION IF EXISTS public.get_professor_offering_terms(TEXT, INTEGER);
CREATE OR REPLACE FUNCTION public.get_professor_offering_terms(
  p_professor_id TEXT,
  p_limit INTEGER DEFAULT 200
)
RETURNS TABLE (
  id BIGINT,
  academic_modality_id BIGINT,
  year INTEGER,
  period_number INTEGER,
  external_key TEXT,
  display_name TEXT
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT DISTINCT
    at.id,
    at.academic_modality_id,
    at.year,
    at.period_number,
    at.external_key,
    at.display_name
  FROM public.academic_term at
  JOIN public.course_offering co ON co.academic_term_id = at.id
  JOIN public.course_offering_group cog ON cog.course_offering_id = co.id
  JOIN public.course_offering_group_professor cogp ON cogp.course_offering_group_id = cog.id
  WHERE cogp.professor_id::text = p_professor_id
    AND co.is_active = TRUE
  ORDER BY at.year DESC, at.period_number DESC, at.id DESC
  LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 200), 500));
$$;

-- ============================================================================
-- 5. DROP starts_on AND ends_on FROM academic_term
-- ============================================================================

ALTER TABLE public.academic_term
  DROP COLUMN IF EXISTS starts_on CASCADE,
  DROP COLUMN IF EXISTS ends_on CASCADE;

-- ============================================================================
-- 6. PERMISSIONS & GRANTS
-- ============================================================================

GRANT EXECUTE ON FUNCTION public.get_active_academic_terms TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_academic_terms_by_plan TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_course_offering_terms TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_professor_offering_terms TO anon, authenticated;

GRANT SELECT ON public.academic_term_event TO anon, authenticated;

DO $$
DECLARE
  v_seq TEXT;
BEGIN
  v_seq := pg_get_serial_sequence('public.academic_term_event', 'id');
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hyperdrive_role') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON public.academic_term_event TO hyperdrive_role;
    IF v_seq IS NOT NULL THEN
      EXECUTE format('GRANT USAGE, SELECT, UPDATE ON SEQUENCE %s TO hyperdrive_role', v_seq);
    END IF;
  END IF;
END $$;

COMMIT;
