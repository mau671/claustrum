-- 0148_room_table.sql
-- Normalises classrooms into a `room` table with a foreign key.
--
-- Today course_offering_meeting.classroom is a free-text column holding values
-- like 'F5-04', 'J01-07' or 'LAB-02'. The ITCR convention is `BUILDING-NN`,
-- where BUILDING can be a single letter (L), letter+number (F5, J01) or an
-- acronym (LAB, LAT, CAM, UTN) and NN is a zero-padded room number.
--
-- Verified against production before writing this migration:
--   - 18015 meetings have a classroom, 6733 are NULL (virtual/remote groups)
--   - 0 values deviate from ^[A-Z0-9]+-[0-9]{2}$
--   - 304 distinct rooms across 61 buildings in 5 campuses
--   - no building appears in more than one campus, but the model allows it
--
-- NULL stays meaningful: a NULL room means "no physical room" (virtual class),
-- not missing data. The column becomes nullable room_id, not a sentinel row.

BEGIN;

-- ============================================================================
-- 1. ROOM TABLE
--    Uniqueness is scoped by campus because nothing guarantees that a building
--    code is globally unique; today it happens to be, but the constraint should
--    not depend on that coincidence.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.room (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id  BIGINT NOT NULL REFERENCES public.campus(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  building   TEXT NOT NULL,
  number     SMALLINT NOT NULL,
  -- Canonical display form: BUILDING-NNN. Generated so it can never drift from
  -- the building/number pair. NOTE: the original definition used lpad, which
  -- truncates numbers longer than the width; 0155 replaces it with a correct
  -- three-digit form.
  code       TEXT GENERATED ALWAYS AS (building || '-' || lpad(number::text, 2, '0')) STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT room_building_format_check CHECK (building ~ '^[A-Z0-9]{1,5}$'),
  CONSTRAINT room_number_range_check CHECK (number BETWEEN 0 AND 999),
  CONSTRAINT room_campus_building_number_key UNIQUE (campus_id, building, number)
);

COMMENT ON TABLE public.room IS
  'Physical rooms/campus spaces parsed from the ITCR schedule guide. '
  'A meeting with no room_id is a virtual or otherwise room-less session.';
COMMENT ON COLUMN public.room.building IS
  'Building identifier as published by the ITCR: L, F5, J01, LAB, LAT, UTN, ...';
COMMENT ON COLUMN public.room.code IS
  'Canonical BUILDING-NN form, e.g. "F5-04". Generated from building and number.';

-- ============================================================================
-- 2. TIMESTAMP TRIGGER (same convention as the other tables)
-- ============================================================================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'set_timestamp_room'
  ) THEN
    CREATE TRIGGER set_timestamp_room
      BEFORE UPDATE ON public.room
      FOR EACH ROW
      EXECUTE FUNCTION public.trigger_set_timestamp();
  END IF;
END $$;

-- ============================================================================
-- 3. ADD THE FOREIGN KEY COLUMN (nullable: NULL means "no physical room")
-- ============================================================================

ALTER TABLE public.course_offering_meeting
  ADD COLUMN IF NOT EXISTS room_id BIGINT
  REFERENCES public.room(id) ON UPDATE CASCADE ON DELETE SET NULL;

-- ============================================================================
-- 4. BACKFILL room ROWS from the existing strings
--    Only rows matching the canonical pattern are imported. Anything else is
--    left as free text in `classroom` and reported, so no data is invented.
-- ============================================================================

INSERT INTO public.room (campus_id, building, number)
SELECT DISTINCT
  co.campus_id,
  split_part(m.classroom, '-', 1) AS building,
  split_part(m.classroom, '-', 2)::SMALLINT AS number
FROM public.course_offering_meeting m
JOIN public.course_offering_group g ON g.id = m.course_offering_group_id
JOIN public.course_offering co ON co.id = g.course_offering_id
WHERE m.classroom IS NOT NULL
  AND m.classroom ~ '^[A-Z0-9]{1,5}-[0-9]{1,3}$'
  AND co.campus_id IS NOT NULL
ON CONFLICT (campus_id, building, number) DO NOTHING;

-- ============================================================================
-- 5. LINK meetings to their room
-- ============================================================================

-- Postgres does not allow referencing the UPDATE target alias inside a JOIN
-- condition of the FROM clause, so resolve the room id in a subquery first.
UPDATE public.course_offering_meeting AS m
SET room_id = resolved.room_id
FROM (
  SELECT
    com.id AS meeting_id,
    r.id AS room_id
  FROM public.course_offering_meeting com
  JOIN public.course_offering_group g ON g.id = com.course_offering_group_id
  JOIN public.course_offering co ON co.id = g.course_offering_id
  JOIN public.room r
    ON r.campus_id = co.campus_id
   AND r.building = split_part(com.classroom, '-', 1)
   AND r.number = split_part(com.classroom, '-', 2)::SMALLINT
  WHERE com.classroom IS NOT NULL
    AND com.classroom ~ '^[A-Z0-9]{1,5}-[0-9]{1,3}$'
    AND com.room_id IS NULL
) AS resolved
WHERE m.id = resolved.meeting_id;

-- ============================================================================
-- 6. REPORT leftovers (should be zero; visible in the migration log if not)
-- ============================================================================

DO $$
DECLARE
  unlinked BIGINT;
  examples TEXT;
BEGIN
  SELECT count(*), string_agg(DISTINCT classroom, ', ')
  INTO unlinked, examples
  FROM public.course_offering_meeting
  WHERE classroom IS NOT NULL
    AND room_id IS NULL;

  IF unlinked > 0 THEN
    RAISE WARNING
      '% meeting(s) kept classroom text but could not be linked to a room: %',
      unlinked, examples;
  END IF;
END $$;

-- ============================================================================
-- 7. INDEXES
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_course_offering_meeting_room_id
  ON public.course_offering_meeting (room_id);

-- The old free-text index has never been used by a query (idx_scan = 0) and
-- becomes redundant once lookups go through room_id.
DROP INDEX IF EXISTS public.idx_course_offering_meeting_classroom;

-- ============================================================================
-- 8. GRANTS (follow the hyperdrive_role pattern used since 0144)
-- ============================================================================

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hyperdrive_role') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON public.room TO hyperdrive_role;
    GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.room_id_seq TO hyperdrive_role;
  END IF;
END $$;

COMMIT;
