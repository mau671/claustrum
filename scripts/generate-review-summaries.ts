/* eslint-disable no-console */
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const { Pool } = pg;

interface ProfessorCandidate {
  professor_id: number;
  full_name: string;
  approved_count: number;
  max_review_id: number;
  last_review_id_analyzed: number | null;
}

interface ReviewRow {
  id: string | number;
  comment: string;
  tags: string[];
  ease_score: string | number | null;
  quality_score: string | number | null;
}

function parseEnvFile(filePath: string): Record<string, string> {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const content = fs.readFileSync(filePath, "utf-8");
  const env: Record<string, string> = {};
  for (const rawLine of content.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIdx = line.indexOf("=");
    if (eqIdx !== -1) {
      const key = line.slice(0, eqIdx).trim();
      let val = line.slice(eqIdx + 1).trim();
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

function escapeSqlString(str: string): string {
  return str.replace(/'/g, "''");
}

function runOpenCodeAgent(prompt: string, timeoutMs = 45000): Promise<string> {
  return new Promise((resolve, reject) => {
    const args = [
      "run",
      "--agent",
      "professor-reviews-summarizer",
      "--model",
      "cliproxy/gemini-3.8-flash#medium",
      "--format",
      "json",
      prompt,
    ];

    const child = spawn("opencode", args, {
      stdio: ["ignore", "pipe", "pipe"],
      env: { ...process.env },
    });

    let stdout = "";
    let stderr = "";
    let isSettled = false;

    const timer = setTimeout(() => {
      if (!isSettled) {
        isSettled = true;
        child.kill("SIGKILL");
        reject(new Error(`opencode process timed out after ${timeoutMs}ms`));
      }
    }, timeoutMs);

    child.stdout.on("data", (chunk: Buffer) => {
      stdout += chunk.toString("utf-8");
    });

    child.stderr.on("data", (chunk: Buffer) => {
      stderr += chunk.toString("utf-8");
    });

    child.on("error", (err) => {
      if (!isSettled) {
        isSettled = true;
        clearTimeout(timer);
        reject(err);
      }
    });

    child.on("close", (code) => {
      if (isSettled) return;
      isSettled = true;
      clearTimeout(timer);

      if (code !== 0) {
        return reject(new Error(`opencode process exited with code ${code}: ${stderr || stdout}`));
      }

      // Parse NDJSON lines
      let accumulatedText = "";
      const lines = stdout.split("\n");
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed) continue;
        try {
          const parsed = JSON.parse(trimmed) as {
            type?: string;
            part?: { type?: string; text?: string };
          };
          if (parsed.type === "text" && parsed.part?.text) {
            accumulatedText += parsed.part.text;
          }
        } catch {
          // Ignore non-json logging lines
        }
      }

      const cleanResult = accumulatedText.trim();
      if (!cleanResult) {
        return reject(new Error(`No text generated by agent. Full stdout:\n${stdout}`));
      }

      resolve(cleanResult);
    });
  });
}

async function main(): Promise<void> {
  const args = process.argv.slice(2).filter((arg) => arg !== "--");
  const isProd = args.includes("--prod");
  const isDryRun = args.includes("--dry-run");
  const isForce = args.includes("--force");

  const limitIndex = args.indexOf("--limit");
  const limit =
    limitIndex !== -1 && args[limitIndex + 1] ? parseInt(args[limitIndex + 1], 10) : null;

  const profIdIndex = args.indexOf("--professor-id");
  const targetProfId =
    profIdIndex !== -1 && args[profIdIndex + 1] ? parseInt(args[profIdIndex + 1], 10) : null;

  let connectionString = process.env.DATABASE_URL;

  if (isProd) {
    const prodEnvPath = path.resolve(process.cwd(), ".env.prod");
    const prodEnv = parseEnvFile(prodEnvPath);
    connectionString = connectionString || prodEnv.DATABASE_URL;
    if (!connectionString) {
      console.error("❌ Error: No DATABASE_URL found in .env.prod");
      process.exit(1);
    }
    console.log("🚀 Reading from PRODUCTION database (.env.prod)");
  } else {
    const devEnvPath = path.resolve(process.cwd(), ".env.dev");
    const devEnv = parseEnvFile(devEnvPath);
    connectionString =
      connectionString ||
      devEnv.DATABASE_URL ||
      "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
    console.log("💻 Reading from LOCAL database (.env.dev)");
  }

  const pool = new Pool({
    connectionString,
    connectionTimeoutMillis: 10000,
  });

  const client = await pool.connect();

  try {
    console.log("🔍 Finding professors with > 10 approved reviews needing AI summary...");

    const candidatesQuery = `
      SELECT 
        p.id AS professor_id,
        p.full_name,
        COUNT(pr.id)::int AS approved_count,
        MAX(pr.id)::bigint AS max_review_id,
        s.last_review_id_analyzed
      FROM public.professor p
      JOIN public.professor_review pr ON pr.professor_id = p.id AND pr.status = 'approved'
      LEFT JOIN public.professor_review_summary s ON s.professor_id = p.id
      ${targetProfId ? `WHERE p.id = ${targetProfId}` : ""}
      GROUP BY p.id, p.full_name, s.last_review_id_analyzed
      HAVING COUNT(pr.id) > 10
         ${isForce ? "" : "AND (s.last_review_id_analyzed IS NULL OR MAX(pr.id) > s.last_review_id_analyzed + 4)"}
      ORDER BY COUNT(pr.id) DESC
      ${limit ? `LIMIT ${limit}` : ""};
    `;

    const { rows: candidates } = await client.query<ProfessorCandidate>(candidatesQuery);

    if (candidates.length === 0) {
      console.log(" All professors with > 10 reviews already have up-to-date AI summaries.");
      return;
    }

    console.log(`📋 Found ${candidates.length} candidate(s) to process.\n`);

    const CONCURRENCY = 16;
    let completedCount = 0;

    async function processCandidate(candidate: ProfessorCandidate) {
      // Fetch reviews using pool directly
      const { rows: reviews } = await pool.query<ReviewRow>(
        `
          SELECT id, comment, tags, ease_score, quality_score
          FROM public.professor_review
          WHERE professor_id = $1 AND status = 'approved'
          ORDER BY id DESC
          LIMIT 60;
        `,
        [candidate.professor_id],
      );

      // Clean reviews (discard 'Ninguno' and very short entries)
      const usefulReviews = reviews.filter(
        (r) =>
          r.comment && r.comment.trim().length > 15 && r.comment.trim().toLowerCase() !== "ninguno",
      );

      if (usefulReviews.length < 5) {
        console.log(
          `   ⚠️ [Prof ${candidate.professor_id}] Skipping: only ${usefulReviews.length} useful descriptive reviews found.`,
        );
        return null;
      }

      const reviewsTextList = usefulReviews
        .map((r, i) => {
          const tagsStr = r.tags && r.tags.length > 0 ? ` [Etiquetas: ${r.tags.join(", ")}]` : "";
          return `${i + 1}. "${r.comment.trim()}"${tagsStr}`;
        })
        .join("\n");

      const prompt = `A continuación tienes las reseñas reales aprobadas del profesor ${candidate.full_name} (ID: ${candidate.professor_id}):\n\n${reviewsTextList}\n\nRedacta la síntesis pedagógica siguiendo estrictamente todas tus directrices de estilo (preferiblemente 1 solo párrafo continuo de unas 100 palabras, máximo 2 breves, sin dos puntos, sin punto y coma, sin guiones largos, oraciones bien articuladas con comas y conectores en español, sin introducciones ni conclusiones genéricas, pudiendo usar negritas, itálicas o subrayados solo si aportan valor visual sin sobrecargar). Devuelve únicamente el texto en Markdown del resumen.`;

      try {
        let summary: string;
        try {
          summary = await runOpenCodeAgent(prompt);
        } catch {
          // Retry once on failure/timeout
          summary = await runOpenCodeAgent(prompt);
        }

        completedCount++;
        console.log(
          `   [${completedCount}/${candidates.length}] Generated summary for ${candidate.full_name} (${summary.length} chars).`,
        );
        if (isDryRun) {
          console.log(
            `\n--- PREVIEW (Prof ${candidate.professor_id}) ---\n${summary}\n---------------\n`,
          );
        }
        return {
          professorId: candidate.professor_id,
          fullName: candidate.full_name,
          summary,
          approvedCount: candidate.approved_count,
          maxReviewId: candidate.max_review_id,
        };
      } catch (agentErr) {
        console.error(
          `   ❌ Failed to generate summary for professor ${candidate.professor_id}:`,
          agentErr,
        );
        return null;
      }
    }

    // Run with worker pool
    const summaryEntries: Array<{
      professorId: number;
      fullName: string;
      summary: string;
      approvedCount: number;
      maxReviewId: number;
    }> = [];

    let candidateIndex = 0;
    async function worker() {
      while (candidateIndex < candidates.length) {
        const index = candidateIndex++;
        const candidate = candidates[index];
        const res = await processCandidate(candidate);
        if (res) {
          summaryEntries.push(res);
        }
      }
    }

    const workers = Array.from({ length: Math.min(CONCURRENCY, candidates.length) }, () =>
      worker(),
    );
    await Promise.all(workers);

    if (summaryEntries.length === 0) {
      console.log("⚠️ No summaries were successfully generated.");
      return;
    }

    if (isDryRun) {
      console.log(
        `✨ Dry run complete. Generated ${summaryEntries.length} preview(s). No seed file written.`,
      );
      return;
    }

    // Write reproducible SQL seed file
    const targetDir = path.resolve(process.cwd(), "data/seeds/review_summaries");
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    const now = new Date();
    const isoTimestamp = now.toISOString().replace(/[-:]/g, "").replace(/\..+/, "Z");
    const fileName = `seed_${isoTimestamp}_summaries.sql`;
    const fullPath = path.join(targetDir, fileName);

    const valuesSql = summaryEntries
      .map((entry) => {
        return `    (${entry.professorId}, '${escapeSqlString(entry.summary)}', ${entry.approvedCount}, ${entry.maxReviewId}, 'cliproxy/gemini-3.8-flash#medium', NOW())`;
      })
      .join(",\n");

    const sqlContent = `-- ============================================================================
-- PROFESSOR REVIEW AI SUMMARIES SEED
-- ============================================================================
-- TEC-DATA-META scope=review_summaries
-- TEC-DATA-META generated_at_utc=${now.toISOString()}
-- TEC-DATA-META total_professors=${summaryEntries.length}

BEGIN;
SET LOCAL search_path = public;

INSERT INTO public.professor_review_summary (
  professor_id,
  summary,
  reviews_analyzed_count,
  last_review_id_analyzed,
  model_used,
  updated_at
)
VALUES
${valuesSql}
ON CONFLICT (professor_id) DO UPDATE SET
  summary = EXCLUDED.summary,
  reviews_analyzed_count = EXCLUDED.reviews_analyzed_count,
  last_review_id_analyzed = EXCLUDED.last_review_id_analyzed,
  model_used = EXCLUDED.model_used,
  updated_at = NOW();

COMMIT;
`;

    fs.writeFileSync(fullPath, sqlContent, "utf-8");
    console.log(`\n🎉 Successfully created reproducible seed file:`);
    console.log(`   ${path.relative(process.cwd(), fullPath)}`);
    console.log(`\n💡 To apply this seed to the database, run:`);
    console.log(`   Local:      pnpm run db:seed -- --summaries`);
    console.log(`   Production: pnpm run db:seed -- --summaries --prod\n`);
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
